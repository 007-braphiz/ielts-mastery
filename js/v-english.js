/* English Proficiency Centre: lessons with practice and short assessments, area tracking, and the Sentence Clinic.
   Feedback is rule-based; it is not generated by an AI model. */
(function () {
  const U = IM.util, esc = U.esc;
  const G = () => IM.data.grammar;
  const lessonRec = id => IM.store.state.proficiency.lessons[id] || { attempts: 0, best: null, wrong: 0, last: null };

  const SOURCES = {
    'Grammar': 'Grammar lessons and the diagnostic', 'Vocabulary': 'Vocabulary Mastery sessions', 'Spelling': 'Dictation Laboratory', 'Punctuation': 'Punctuation lessons and dictation',
    'Sentence construction': 'Sentence construction lessons', 'Reading comprehension': 'Reading practice', 'Listening comprehension': 'Listening practice and dictation',
    'Paraphrasing': 'Paraphrasing lesson', 'Academic writing': 'Academic writing lessons and Writing Coach', 'Pronunciation': 'Speaking self-ratings', 'Fluency': 'Speaking practice',
    'Cohesion and logical expression': 'Cohesion lesson and Writing Coach'
  };

  /* ---------------------------------------------------------------- shared helpers (also used by Writing Coach) */
  IM.notebook = {
    add(issue, source) {
      if (!issue || !issue.sentence) return null;
      const s = IM.store.state;
      if (s.writing.notebook.some(n => n.sentence === issue.sentence && n.ruleId === issue.ruleId)) return null;
      const entry = { id: U.uid(), date: U.today(), sentence: issue.sentence, category: issue.cat, ruleId: issue.ruleId, msg: issue.msg, principle: issue.principle, improved: issue.corrected || '', lesson: issue.lesson || '', source: source || 'writing', attempts: [], resolved: false };
      IM.store.update(st => { st.writing.notebook.push(entry); if (st.writing.notebook.length > 300) st.writing.notebook.shift(); });
      return entry;
    },
    /* Does a new attempt avoid the original error? */
    check(entry, text) {
      const words = U.countWords(text);
      if (words < 4) return { fixed: false, why: 'Write a complete sentence (at least 4 words).' };
      if (text.trim() === entry.sentence.trim()) return { fixed: false, why: 'This is the same sentence. Change the part containing the error.' };
      const an = IM.tutor.analyse(text);
      const same = an.issues.filter(i => i.ruleId === entry.ruleId || (i.cat === entry.category && i.confidence === 'sure'));
      if (same.length) return { fixed: false, why: `The same kind of error is still present: ${same[0].msg}` };
      return { fixed: true, why: 'No error of this type was detected.' };
    },
    retry(entryId, text) {
      const s = IM.store.state;
      const e = s.writing.notebook.find(n => n.id === entryId);
      if (!e) return null;
      const r = IM.notebook.check(e, text);
      IM.store.update(() => { e.attempts.push({ ts: Date.now(), text, fixed: r.fixed }); if (r.fixed) e.resolved = true; });
      IM.srs.record('clinic:' + e.ruleId, r.fixed, { context: 'notebook', title: e.category });
      IM.analytics.recordArea('Sentence construction', r.fixed ? 1 : 0, 1);
      IM.store.logActivity('clinic', 'notebook', e.category, r.fixed ? 1 : 0, 1, 2);
      return r;
    }
  };

  const SEEDS = [
    'Many peoples think that technology is important.', 'She have a lot of informations about the course.', 'I am agree with this opinion.', 'There is many reasons for this problem.',
    'People which live in cities have less space.', 'This will be more better for everyone.', 'Students must to submit their work on time.', 'He did a mistake in the final exam.',
    'I would of studied harder if I had known.', 'Although it was expensive, but they bought it.', 'Each students has a different learning style.', 'The film was better then I expected.',
    'They discussed about the problem for an hour.', 'She is interested on art history.'
  ];

  function nextClinicCase() {
    const s = IM.store.state;
    const open = s.writing.notebook.filter(n => !n.resolved)[0];
    if (open) return { entry: open, source: 'notebook', sentence: open.sentence, ruleId: open.ruleId, cat: open.category, msg: open.msg, principle: open.principle || G().principles[open.category] || '', corrected: open.improved, lesson: open.lesson, match: '' };
    const cases = SEEDS.map(sent => { const a = IM.tutor.analyse(sent); const iss = a.issues.find(i => i.confidence === 'sure') || a.issues[0]; return iss ? { source: 'example', sentence: sent, ruleId: iss.ruleId, cat: iss.cat, msg: iss.msg, principle: iss.principle, corrected: iss.corrected, lesson: iss.lesson, match: iss.match } : null; }).filter(Boolean);
    cases.sort((a, b) => { const ra = IM.srs.get('clinic:' + a.ruleId), rb = IM.srs.get('clinic:' + b.ruleId); return ((ra ? ra.box : -1) - (rb ? rb.box : -1)) || Math.random() - 0.5; });
    return cases[0];
  }

  function highlight(sentence, match) {
    if (!match) return esc(sentence);
    const i = sentence.toLowerCase().indexOf(match.toLowerCase());
    if (i < 0) return esc(sentence);
    return esc(sentence.slice(0, i)) + `<span class="hl">${esc(sentence.slice(i, i + match.length))}</span>` + esc(sentence.slice(i + match.length));
  }

  IM.views.english = function (root, params) {
    const S = () => IM.store.state;
    let tab = params.tab || (params.review ? 'review' : 'overview');
    let lesson = null;      // current lesson object
    let ls = null;          // lesson session
    let clinic = null;      // clinic session

    /* ----- overview ----- */
    function overviewHtml() {
      const st = IM.analytics.areaStats();
      const rows = IM.data.scoring.areas.map(a => { const x = st[a]; return `<tr><td><b>${esc(a)}</b><br><span class="small muted">${esc(SOURCES[a])}</span></td><td style="min-width:130px">${x.attempts ? IM.ui.bar(x.pct, a, x.pct >= 80 ? 'good' : x.pct >= 60 ? '' : 'warn') : '<span class="muted small">no data yet</span>'}</td><td>${x.attempts ? x.pct + '%' : '—'}</td><td>${x.attempts}</td><td>${x.recent == null ? '—' : x.recent + '%'}</td></tr>`; }).join('');
      const weak = Object.entries(st).filter(([, v]) => v.attempts >= 5 && v.pct < 60).map(([k]) => k);
      return `<div class="card"><h2>Language skills tracked separately</h2><p class="small muted">Each area is measured on its own so that strong vocabulary cannot hide persistent grammar weaknesses.</p>
        <div class="table-wrap"><table class="t"><thead><tr><th>Area</th><th>Accuracy</th><th></th><th>Answers</th><th>Recent</th></tr></thead><tbody>${rows}</tbody></table></div>
        ${weak.length ? `<p class="note"><b>Needs attention:</b> ${weak.map(esc).join(', ')}. The matching lessons below are recommended before more difficult exercises.</p>` : ''}
        ${!S().diagnostic.done ? `<div class="note info">No baseline yet. <a href="#/diagnostic">Take the diagnostic assessment</a> or simply start a lesson.</div>` : ''}</div>`;
    }

    /* ----- lessons ----- */
    function lessonListHtml() {
      return `<div class="grid c2">${G().lessons.map(l => { const r = lessonRec(l.id); return `<div class="card"><div class="row space"><h3 style="margin:0">${esc(l.title)}</h3>${r.best === 2 ? '<span class="badge good">assessment passed</span>' : r.attempts ? '<span class="badge info">in progress</span>' : '<span class="badge">new</span>'}</div>
        <p class="small muted">Area: ${esc(l.area)} · ${l.questions.length} questions${r.attempts ? ` · best assessment ${r.best == null ? '—' : r.best + '/2'}` : ''}${r.wrong >= 3 ? ' · <b>remedial review suggested</b>' : ''}</p><button class="btn small" data-lesson="${esc(l.id)}">${r.attempts ? 'Open lesson' : 'Start lesson'}</button></div>`; }).join('')}</div>`;
    }

    function openLesson(id) {
      lesson = G().lessons.find(l => l.id === id);
      ls = { stage: 'learn', qi: 0, answered: false, results: [], assess: [], retry: [] };
      drawLesson();
    }
    function qBlock(q, idx, total, label) {
      return `<div class="card"><p class="muted small">${label} ${idx + 1} of ${total}</p><p style="font-size:1.08rem">${esc(q.q)}</p>${q.opts.map((o, k) => `<button class="optbtn" data-ans="${k}">${'ABCD'[k]}. ${esc(o)}</button>`).join('')}</div>`;
    }
    function drawLesson() {
      const l = lesson;
      const head = `<a class="back" href="#" data-act="lessons">← All lessons</a><h1>${esc(l.title)}</h1><div class="progress-steps">${['learn', 'practice', 'assess', 'done'].map((s, i) => `<span class="${['learn', 'practice', 'assess', 'done'].indexOf(ls.stage) >= i ? 'on' : ''}"></span>`).join('')}</div>`;
      if (ls.stage === 'learn') {
        root.innerHTML = head + `<div class="card">${l.explain}<h4>Examples</h4><ul>${l.examples.map(x => `<li>${x}</li>`).join('')}</ul><button class="btn" data-act="topractice">Start practice</button></div>`;
      } else if (ls.stage === 'practice' || ls.stage === 'retry') {
        const list = ls.stage === 'practice' ? l.questions.slice(0, 3) : ls.retry;
        const q = list[ls.qi];
        let h = head + qBlock(q, ls.qi, list.length, ls.stage === 'practice' ? 'Practice question' : 'Try again');
        if (ls.answered) {
          const r = ls.last;
          h = head + `<div class="card"><p class="muted small">${ls.stage === 'practice' ? 'Practice question' : 'Try again'} ${ls.qi + 1} of ${list.length}</p><p style="font-size:1.08rem">${esc(q.q)}</p>${q.opts.map((o, k) => `<div class="optbtn ${k === q.a ? 'right' : k === r.chosen ? 'wrong' : ''}">${'ABCD'[k]}. ${esc(o)}</div>`).join('')}
            <div class="explain ${r.ok ? 'good' : 'wrong'}"><b>${r.ok ? '✔ Correct' : '✘ Not quite'}.</b> ${esc(q.why)}</div>
            ${r.ok ? '' : `<div class="formrow"><label class="field" for="why">In your own words, why is “${esc(q.opts[q.a])}” correct? <span class="muted small">(required, at least 5 words)</span></label><textarea id="why" rows="2" style="min-height:70px"></textarea></div>`}
            <button class="btn" data-act="qnext">${ls.qi + 1 < list.length ? 'Next question' : (ls.stage === 'practice' ? 'Continue' : 'Continue to the assessment')}</button></div>`;
        }
        root.innerHTML = h;
      } else if (ls.stage === 'assess') {
        const qs = l.questions.slice(3);
        const q = qs[ls.qi];
        root.innerHTML = head + `<div class="note info">Short assessment: ${qs.length} questions. Answers are marked together at the end.</div>` + qBlock(q, ls.qi, qs.length, 'Assessment question') + (ls.qi ? '' : '');
      } else {
        const score = ls.assess.filter(Boolean).length;
        const wrong = ls.results.filter(r => !r.ok).length;
        root.innerHTML = head + `<div class="card"><h2>Lesson result</h2><div class="grid c3">${IM.ui.stat('Practice', ls.results.filter(r => r.stage === 'practice' && r.ok).length + '/3')}${IM.ui.stat('Assessment', score + '/' + ls.assess.length)}${IM.ui.stat('Status', score === ls.assess.length ? 'Passed' : 'Review')}</div>
          ${ls.assessDetail.map((r, i) => `<div class="explain ${r.ok ? 'good' : 'wrong'}"><b>${r.ok ? '✔' : '✘'} ${esc(r.q.q)}</b><br>${r.ok ? '' : `Correct answer: ${esc(r.q.opts[r.q.a])}. `}${esc(r.q.why)}</div>`).join('')}
          ${score < ls.assess.length ? '<p class="note">Re-read the explanation and try the lesson again. Questions you missed will return in your revision queue.</p>' : '<p class="note good">Well done. The questions will still return for review on a spaced schedule to confirm the learning lasts.</p>'}
          <div class="row"><button class="btn" data-act="again">Repeat this lesson</button><button class="btn secondary" data-act="lessons">All lessons</button><button class="btn secondary" data-act="clinic">Apply it in the Sentence Clinic</button></div></div>`;
      }
    }

    function record(q, ok, stage) {
      IM.srs.record('gram:' + q.id, ok, { context: stage, title: lesson.title });
      IM.analytics.recordArea(lesson.area, ok ? 1 : 0, 1);
      IM.store.update(s => {
        const r = s.proficiency.lessons[lesson.id] || (s.proficiency.lessons[lesson.id] = { attempts: 0, best: null, wrong: 0, last: null });
        if (!ok) r.wrong++;
      });
    }

    function answer(k) {
      const l = lesson;
      if (ls.stage === 'practice' || ls.stage === 'retry') {
        const list = ls.stage === 'practice' ? l.questions.slice(0, 3) : ls.retry;
        const q = list[ls.qi];
        if (ls.answered) return;
        const ok = k === q.a;
        record(q, ok, ls.stage);
        ls.results.push({ q, ok, stage: ls.stage });
        ls.answered = true; ls.last = { ok, chosen: k };
        drawLesson();
      } else if (ls.stage === 'assess') {
        const qs = l.questions.slice(3), q = qs[ls.qi];
        const ok = k === q.a;
        ls.assess.push(ok);
        (ls.assessDetail = ls.assessDetail || []).push({ q, ok });
        record(q, ok, 'assessment');
        ls.results.push({ q, ok, stage: 'assessment' });
        if (ls.qi + 1 < qs.length) { ls.qi++; drawLesson(); }
        else {
          const score = ls.assess.filter(Boolean).length;
          IM.store.update(s => { const r = s.proficiency.lessons[l.id]; r.attempts++; r.last = score; r.best = Math.max(r.best || 0, score); if (score === qs.length) r.completedAt = U.today(); });
          IM.store.logActivity('english', 'lesson', l.title + ': ' + score + '/' + qs.length, score, qs.length, 8);
          ls.stage = 'done'; drawLesson();
        }
      }
    }

    function qnext() {
      const l = lesson;
      const list = ls.stage === 'practice' ? l.questions.slice(0, 3) : ls.retry;
      if (!ls.last.ok) {
        const why = (U.$('#why', root) || {}).value || '';
        if (U.countWords(why) < 5) { U.toast('Explain in at least 5 words before continuing.', 'warn'); return; }
        ls.retryNeeded = (ls.retryNeeded || []).concat(list[ls.qi]);
      }
      ls.answered = false; ls.last = null;
      if (ls.qi + 1 < list.length) { ls.qi++; }
      else if (ls.stage === 'practice' && ls.retryNeeded && ls.retryNeeded.length) { ls.stage = 'retry'; ls.retry = ls.retryNeeded; ls.retryNeeded = []; ls.qi = 0; }
      else { ls.stage = 'assess'; ls.qi = 0; ls.retryNeeded = []; }
      drawLesson();
    }

    /* ----- review of due grammar items ----- */
    function drawReview() {
      const due = IM.srs.due('gram:');
      const all = G().lessons.flatMap(l => l.questions.map(q => Object.assign({ lessonId: l.id, area: l.area, lessonTitle: l.title }, q)));
      const items = due.map(d => all.find(q => 'gram:' + q.id === d.key)).filter(Boolean).slice(0, 8);
      if (!items.length) { root.innerHTML = '<a class="back" href="#/english">← Back</a><h1>Grammar review</h1>' + IM.ui.empty('No grammar questions are due for review.', '<a class="btn" href="#/english?tab=lessons">Open the lessons</a>'); return; }
      ls = { review: items, qi: 0, correct: 0, answered: false };
      drawReviewQ();
    }
    function drawReviewQ() {
      const q = ls.review[ls.qi];
      if (!q) {
        IM.store.logActivity('english', 'review', `${ls.correct}/${ls.review.length}`, ls.correct, ls.review.length, 5);
        root.innerHTML = `<h1>Grammar review complete</h1><div class="card"><p>You answered <b>${ls.correct}</b> of ${ls.review.length} correctly. Items return on a schedule that depends on your answer.</p><a class="btn" href="#/english">Back to the centre</a></div>`; return;
      }
      root.innerHTML = `<h1>Grammar review</h1><div class="card"><p class="muted small">${esc(q.lessonTitle)} · question ${ls.qi + 1} of ${ls.review.length}</p><p style="font-size:1.08rem">${esc(q.q)}</p>
        ${q.opts.map((o, k) => `<button class="optbtn ${ls.answered ? (k === q.a ? 'right' : k === ls.chosen ? 'wrong' : '') : ''}" ${ls.answered ? 'disabled' : ''} data-rv="${k}">${'ABCD'[k]}. ${esc(o)}</button>`).join('')}
        ${ls.answered ? `<div class="explain ${ls.chosen === q.a ? 'good' : 'wrong'}">${esc(q.why)}</div><button class="btn" data-act="rvnext">Next</button>` : ''}</div>`;
    }

    /* ----- Sentence Clinic ----- */
    function startClinic() {
      const c = nextClinicCase();
      if (!c) { root.innerHTML = '<h1>Sentence Clinic</h1>' + IM.ui.empty('No cases available.'); return; }
      clinic = Object.assign({ step: 1 }, c);
      drawClinic();
    }
    const STEPS = ['Your sentence', 'The precise error', 'The principle', 'Corrected version', 'Why it is better', 'Your turn', 'Result'];
    function drawClinic() {
      const c = clinic;
      const head = `<a class="back" href="#" data-act="cliniclist">← Sentence Clinic</a><h1>Sentence Clinic</h1><div class="progress-steps">${STEPS.map((s, i) => `<span class="${i < c.step ? 'on' : ''}"></span>`).join('')}</div><p class="muted small">Step ${c.step} of 7: ${STEPS[c.step - 1]} · ${c.source === 'notebook' ? 'from your error notebook' : 'practice sentence'}</p>`;
      let body = '';
      switch (c.step) {
        case 1: body = `<div class="card"><p style="font-size:1.2rem" class="highlighted">${esc(c.sentence)}</p><p>Read the sentence. Can you see what is wrong? Think first, then continue.</p><button class="btn" data-act="cnext">Show me the error</button></div>`; break;
        case 2: body = `<div class="card"><p style="font-size:1.2rem" class="highlighted">${highlight(c.sentence, c.match)}</p><p><b>Error type:</b> ${esc(c.cat)}</p><p>${esc(c.msg)}</p><button class="btn" data-act="cnext">Explain the principle</button></div>`; break;
        case 3: body = `<div class="card"><h3>The underlying principle</h3><p>${esc(c.principle || G().principles[c.cat] || 'Check the related lesson.')}</p>${c.lesson ? `<p class="small"><a href="#" data-lesson="${esc(c.lesson)}">Open the related lesson →</a></p>` : ''}<button class="btn" data-act="cnext">Show the corrected version</button></div>`; break;
        case 4: body = `<div class="card"><h3>Corrected or improved version</h3><p style="font-size:1.2rem" class="highlighted">${c.corrected ? esc(c.corrected) : '<span class="muted">(No automatic correction is available. Apply the principle yourself.)</span>'}</p><button class="btn" data-act="cnext">Why is this better?</button></div>`; break;
        case 5: body = `<div class="card"><h3>Why the revision is better</h3><p>${esc(c.msg)}</p><p class="small muted">Original: <i>${esc(c.sentence)}</i><br>Revised: <i>${esc(c.corrected || '—')}</i></p><p>The revised sentence follows the principle, so a reader (or examiner) is not distracted by the error and your <b>${c.cat === 'Spelling' ? 'spelling' : 'grammatical accuracy'}</b> is stronger.</p><button class="btn" data-act="cnext">Now it is your turn</button></div>`; break;
        case 6: body = `<div class="card"><h3>Apply the principle yourself</h3>
          <div class="formrow"><label class="field" for="c-why">1. In your own words, why is the corrected version right? <span class="muted small">(at least 6 words)</span></label><textarea id="c-why" rows="2" style="min-height:70px"></textarea></div>
          <div class="formrow"><label class="field" for="c-new">2. Write a <b>new</b> sentence (different topic) that uses the same principle correctly. <span class="muted small">(at least 6 words)</span></label><textarea id="c-new" rows="2" style="min-height:70px"></textarea></div>
          <button class="btn" data-act="ccheck">Check my sentence</button></div>`; break;
        default: {
          const r = c.result;
          body = `<div class="card"><h3>${r.ok ? '✔ Applied independently' : '✘ Not yet'}</h3><p class="highlighted">${esc(c.newSentence)}</p><p>${esc(r.why)}</p>
            ${r.ok ? '<p class="note good">The principle appears to be applied correctly in your own sentence. This check only looks for the error pattern; it cannot judge meaning.</p>' : '<p class="note">Try again with a different sentence. The case will return in your revision queue.</p>'}
            <p>Could you have produced this without help? ${c.independent == null ? '<button class="btn small secondary" data-ind="1">Yes</button> <button class="btn small secondary" data-ind="0">Not quite</button>' : `<b>${c.independent ? 'Yes' : 'Not quite'}</b> (recorded)`}</p>
            <div class="row"><button class="btn" data-act="cclinic">Next case</button>${r.ok ? '' : '<button class="btn secondary" data-act="cretry">Try again</button>'}</div></div>`;
        }
      }
      root.innerHTML = head + body;
    }
    function clinicCheck() {
      const c = clinic;
      const why = U.$('#c-why', root).value.trim(), sent = U.$('#c-new', root).value.trim();
      if (U.countWords(why) < 6) { U.toast('Explain the rule in at least 6 words.', 'warn'); return; }
      if (U.countWords(sent) < 6) { U.toast('Write a new sentence of at least 6 words.', 'warn'); return; }
      const probe = { sentence: c.sentence, ruleId: c.ruleId, category: c.cat };
      const r = IM.notebook.check(probe, sent);
      c.newSentence = sent; c.explanation = why; c.result = { ok: r.fixed, why: r.why };
      IM.srs.record('clinic:' + c.ruleId, r.fixed, { context: 'clinic', title: c.cat });
      IM.analytics.recordArea('Sentence construction', r.fixed ? 1 : 0, 1);
      IM.store.update(s => {
        s.proficiency.clinic.push({ date: U.today(), ruleId: c.ruleId, cat: c.cat, ok: r.fixed, independent: null });
        if (s.proficiency.clinic.length > 200) s.proficiency.clinic.shift();
        if (c.entry) { const e = s.writing.notebook.find(n => n.id === c.entry.id); if (e) { e.attempts.push({ ts: Date.now(), text: sent, fixed: r.fixed }); if (r.fixed) e.resolved = true; } }
      });
      IM.store.logActivity('clinic', 'clinic', c.cat, r.fixed ? 1 : 0, 1, 5);
      c.step = 7; drawClinic();
    }
    function clinicHomeHtml() {
      const open = S().writing.notebook.filter(n => !n.resolved).length;
      const log = S().proficiency.clinic;
      const ok = log.filter(x => x.ok).length;
      return `<div class="card"><h2>Sentence Clinic</h2><p>A seven-step routine for turning an error into a skill: see your sentence, find the precise error, understand the principle, study the correction, learn why it is better, explain it, and then apply it in a brand-new sentence.</p>
        <p class="small muted">Cases come from your own error notebook first (${open} open), then from a built-in practice set. Feedback is rule-based pattern checking, not an AI model.</p>
        ${log.length ? `<p>Applied independently: <b>${ok}</b> of ${log.length} cases.</p>` : ''}<button class="btn" data-act="cclinic">Start a case</button></div>
        ${log.length ? `<div class="card"><h3>Recent cases</h3><ul>${log.slice(-6).reverse().map(x => `<li>${U.fmtDate(x.date)}: ${esc(x.cat)} — ${x.ok ? '✔ applied' : '✘ needs practice'}</li>`).join('')}</ul></div>` : ''}`;
    }

    /* ----- main draw ----- */
    function draw() {
      lesson = null; clinic = null;
      if (tab === 'review') { drawReview(); return; }
      const tabs = [['overview', 'Overview'], ['lessons', 'Lessons'], ['clinic', 'Sentence Clinic']];
      let inner;
      if (tab === 'overview') inner = overviewHtml() + `<div class="row"><a class="btn" href="#/diagnostic">${S().diagnostic.done ? 'Retake the diagnostic' : 'Take the diagnostic'}</a><button class="btn secondary" data-tab="lessons">Browse lessons</button></div>`;
      else if (tab === 'lessons') inner = lessonListHtml();
      else inner = clinicHomeHtml();
      root.innerHTML = `<h1>English Proficiency Centre</h1><div class="tabs">${tabs.map(t => `<button class="tab ${tab === t[0] ? 'active' : ''}" data-tab="${t[0]}">${t[1]}</button>`).join('')}</div>${inner}`;
    }

    root.addEventListener('click', e => {
      const tb = e.target.closest('[data-tab]'); if (tb) { tab = tb.dataset.tab; draw(); return; }
      const ln = e.target.closest('[data-lesson]'); if (ln) { e.preventDefault(); openLesson(ln.dataset.lesson); return; }
      const an = e.target.closest('[data-ans]'); if (an && lesson) { answer(Number(an.dataset.ans)); return; }
      const rv = e.target.closest('[data-rv]');
      if (rv && ls && ls.review && !ls.answered) {
        const q = ls.review[ls.qi], k = Number(rv.dataset.rv), ok = k === q.a;
        ls.answered = true; ls.chosen = k; if (ok) ls.correct++;
        IM.srs.record('gram:' + q.id, ok, { context: 'review', title: q.lessonTitle });
        IM.analytics.recordArea(q.area, ok ? 1 : 0, 1);
        drawReviewQ(); return;
      }
      const ind = e.target.closest('[data-ind]');
      if (ind && clinic) { clinic.independent = ind.dataset.ind === '1'; IM.store.update(s => { const l = s.proficiency.clinic; if (l.length) l[l.length - 1].independent = clinic.independent; }); drawClinic(); return; }
      const a = e.target.closest('[data-act]'); if (!a) return;
      switch (a.dataset.act) {
        case 'lessons': e.preventDefault(); tab = 'lessons'; draw(); break;
        case 'topractice': ls.stage = 'practice'; ls.qi = 0; drawLesson(); break;
        case 'qnext': qnext(); break;
        case 'again': openLesson(lesson.id); break;
        case 'clinic': tab = 'clinic'; draw(); break;
        case 'rvnext': ls.qi++; ls.answered = false; drawReviewQ(); break;
        case 'cclinic': startClinic(); break;
        case 'cliniclist': e.preventDefault(); tab = 'clinic'; draw(); break;
        case 'cnext': clinic.step++; drawClinic(); break;
        case 'ccheck': clinicCheck(); break;
        case 'cretry': clinic.step = 6; drawClinic(); break;
      }
    });
    if (params.lesson) openLesson(params.lesson); else draw();
    if (tab === 'clinic' && params.start) startClinic();
  };
})();
